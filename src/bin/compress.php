require __DIR__ . "/../SimpleLoader.php";

/**
 * Phar Archive Builder
 *
 * This script is a CLI tool for creating self-contained `.phar` archives
 * from a given source directory and optional vendor directories.
 *
 * Features:
 * - Recursively scans and adds files into the archive, stripping
 *   whitespace and comments from PHP files unless `--debug` is used.
 * - Optionally adds header, bootstrap, CLI stub (default.php) and
 *   web stub (index.php).
 * - Generates a bootstrap stub that configures Phar, handles CLI vs web
 *   entry points, and optionally enables URL rewrite if `--rewrite` is set.
 *
 * Usage:
 *   compress.php [<Options>] <Source Directory>
 *
 * This script is intended as a build tool and not as part of the public API.
 *
 * @ignore
 */

use gabbro\SimpleLoader;
use gabbro\collection\ArrayList;
use gabbro\collection\ArgV;
use gabbro\collection\ArgV\ArrayOption;
use gabbro\collection\ArgV\Option;
use gabbro\collection\ArgV\Flag;
use gabbro\collection\ArgV\Operand;
use gabbro\io\IOStream;
use gabbro\utils\Text;
 
$loader = SimpleLoader::getInstance();
$loader->enableAutoload();

$stdout = IOStream::getInstance(IOStream::STDOUT);

/**
 * @ignore
 *
 * @param string $msg
 * @return never
 */
function doExit(string $msg): void {
    $stderr = IOStream::getInstance(IOStream::STDERR);
    $stderr->println($msg);
    
    exit(1);
}

/* ==================================================
 * Create and extract command line options
 */

$arg = new stdClass();
$arg->Parser = new ArgV($argv);

$arg->Parser->parseAll(
    $arg->help = Flag::withDescription(
            "Show this help section.", 
            "--help", "-h"
    ),
    
    $arg->debug = Flag::withDescription(
            "Create a debug archive. By default all comments and redundant white spaces will be removed from the source files. If this is defined then source files are added as is.", 
            "--debug", "-d"
    ),
    
    $arg->rewrite = Flag::withDescription(
            "Enable rewrite on web requests. This only has an affect if web-stub is also declared which will enable URL rewrite that targets the index.php stub.", 
            "--rewrite"
    ),
    
    $arg->name = Option::withDescription(
            "NAME", 
            "Set the archive name. This will be used as the alias within the archive.", 
            "--name"
    ),
    
    $arg->bootstrap = Option::withDescription(
            "FILE", 
            "Declare a bootstrap file. This is normally auto generated by this script and will setup the phar, deal with stub and web stub files etc. This is the outermost stub in the phar archive and must include things like __HALT_COMPILER(), mapPhar etc.", 
            "--bootstrap"
    ),
    
    $arg->header = Option::withDescription(
            "FILE", 
            "A header file is one that is always included by the default bootstrap. It will be added to header.php and will be included no mater if the request targets stub or web stub.", 
            "--header"
    ),
    
    $arg->meta = Option::withDescription(
            "FILE", 
            "A file with additional content. There are no restrictions to this file, it will be added to the archive simply as meta and can be used by the the header, stub or source files.", 
            "--meta"
    ),
    
    $arg->stub = Option::withDescription(
            "FILE", 
            "Declare a default stub file. If no web stub was added then this will be used as default for any access to the archive. Otherwise this will only be accessed through CLI calls. It will be added as default.php within the archive.", 
            "--stub"
    ),
    
    $arg->webstub = Option::withDescription(
            "FILE", 
            "Declare a web stub file. This will be used when the archive is accessed via a Web server. It will be added as index.php within the archive.", 
            "--web-stub"
    ),
    
    $arg->vendor = ArrayOption::withDescription(
            "PATH", 
            "Add one or more vendor directories. These will be added to vendor/ within the archive.", 
            "--vendor"
    ),
    
    $arg->output = Option::withDescription(
            "FILE", 
            "Path and/or file to create e.g. myapp.phar.", 
            "--output"
    ),
    
    $arg->source = Operand::withDescription(
            "Source Directory",
            "Path to the source files for this archive. These will be added to src/ within the archive.",
            0
    )
);

if ($arg->help->isSet()) {
    $stdout->println( $arg->Parser->buildHelp("Usage: compress.php [<Options>] <Source Directory>") );
    exit(0);
    
} else if (!$arg->Parser->isConsumed()) {
    doExit("Invalid arguments. Use -h or --help to see all options.");
}

/* ==================================================
 * Convert command line options into script config
 */

$cfg = new stdClass();
$cfg->name = $arg->name->getValue("app.phar");
$cfg->output = $arg->output->getValue( $cfg->name );
$cfg->source = $arg->source->getValue();
$cfg->vendor = $arg->vendor->toArray();
$cfg->stub = $arg->stub->getValue();
$cfg->webstub = $arg->webstub->getValue();
$cfg->header = $arg->header->getValue();
$cfg->meta = $arg->meta->getValue();
$cfg->bootstrap = $arg->bootstrap->getValue();
$cfg->debug = $arg->debug->isSet();
$cfg->rewrite = $arg->rewrite->isSet();

if ($cfg->source === null || !is_dir($cfg->source)) {
    doExit("Missing source directory");
    
} else if (!is_readable($cfg->source)) {
    doExit("The source directory is not readable");
    
} else if (!is_dir( dirname($cfg->output) )) {
    doExit("Invalid output directory");
    
} else if (!is_writable( dirname($cfg->output) )) {
    doExit("The destination directory is not writable");
    
} else if (is_file($cfg->output) && !unlink($cfg->output)) {
    doExit("Failed to remove the old build");
}

foreach ([$cfg->meta, $cfg->header, $cfg->bootstrap, $cfg->stub, $cfg->webstub] as $file) {
    if ($file !== null && !is_file($file)) {
        doExit("Declared file '$file' does not exist");
    
    } else if ($file !== null && !is_readable($file)) {
        doExit("Declared file '$file' is not readable");
    }
}

foreach ($cfg->vendor as &$path) {
    if (!is_dir($path)) {
        doExit("Missing vendor directory '$path'");
        
    } else if (!is_readable($path)) {
        doExit("The vendor directory '$path' is not readable");
    }
    
    $path = realpath($path) ?: $path;
}

$cfg->source = realpath($cfg->source) ?: $cfg->source;

/* ==================================================
 * Create the archive and start adding files
 */
 
$phar = new Phar($cfg->output, 0, $cfg->name);
$scanDirs = [
    "src" => [$cfg->source],
    "vendor" => $cfg->vendor
];

foreach ($scanDirs as $type => $dirs) {
    foreach ($dirs as $dir) {
        $stdout->println("Compiling %s into %s", $dir, basename($cfg->output));

        $iterator = new RecursiveIteratorIterator(
                            new RecursiveDirectoryIterator($dir, FilesystemIterator::FOLLOW_SYMLINKS|FilesystemIterator::SKIP_DOTS|FilesystemIterator::CURRENT_AS_PATHNAME),
                                RecursiveIteratorIterator::SELF_FIRST);
                 
        /** @var string $file */
        foreach ($iterator as $file) {
            if (is_file($file)) {
                $local_file = "$type" . DIRECTORY_SEPARATOR . substr($file, strlen($dir)+1);
                
                $stdout->println("  Adding %s", $local_file);
                
                if (!$cfg->debug && str_ends_with($local_file, ".php")) {
                    $phar->addFromString($local_file, php_strip_whitespace($file));

                } else {
                    $phar->addFile($file, $local_file);
                }
            }
        }
    }
}

/* ==================================================
 * Create the stub file
 */
 
if ($cfg->bootstrap === null) {
    $bootstrap = Text::normalizeIndent("
        #!/usr/bin/env php
        <?php
        if (!in_array(\"phar\", stream_get_wrappers()) || !class_exists(\"Phar\", false)) {
            throw new Exception(\"Phar extension missing\");
        }
        
        // Detect CLI or Web
        \$isCli = (PHP_SAPI === \"cli\" || PHP_SAPI === \"phpdbg\");
        
        // These are statically included during build to provide a faster lookup of static states.
        \$hasStub = ".($cfg->stub === null ? "false" : "true").";
        \$hasWebStub = ".($cfg->webstub === null ? "false" : "true").";
        \$hasHeader = ".($cfg->header === null ? "false" : "true").";
        
        if (\$isCli || !\$hasWebStub) {
            if (!\$hasStub) {
                throw new Exception(\"Failed to initialize this archive. This is a pure archive and cannot be included or run as a web location.\");
            }
            
            Phar::mapPhar(\"{$cfg->name}\");

            if (\$hasHeader) {
                require \"phar://{$cfg->name}/header.php\";
            }
            
            require \"phar://{$cfg->name}/default.php\";
            exit;
        }

        \$inPhar = (bool) (Phar::running(false));
        
        Phar::interceptFileFuncs();
        
        if (\$inPhar) {
            Phar::mungServer([\"REQUEST_URI\", \"SCRIPT_NAME\", \"SCRIPT_FILENAME\"]);
        }
        
        Phar::mapPhar(\"{$cfg->name}\");
        
        if (\$hasHeader) {
            require \"phar://{$cfg->name}/header.php\";
        }
        
        \$path = parse_url(\$_SERVER[\"REQUEST_URI\"], PHP_URL_PATH);
        \$path = trim(preg_replace(\"#^.*/" . preg_quote("{$cfg->output}", "#") . "/?#\", \"\", \$path), \"/\");

        if (\$path === \"\" || \$path === \"index.php\") {
            require \"phar://{$cfg->name}/index.php\";
            exit;
        }
        
        \$file = !empty(\$path) ? \"phar://ebudget.phar/{\$path}\" : null;
    ");
    
    if ($cfg->rewrite) {
        $bootstrap .= Text::normalizeIndent("
            if (\$file !== null && file_exists(\$file)) {
                require \$file;
                
            } else {
                require \"phar://{$cfg->name}/index.php\";
            }
        ");
        
    } else {
        $bootstrap .= Text::normalizeIndent("
            if (\$file !== null && file_exists(\$file)) {
                require \$file;
                exit;
            }
            
            http_response_code(404);
        ");
    }
    
    $bootstrap .= Text::normalizeIndent("
        exit;
        __HALT_COMPILER();
    ");
    
} else {
    $bootstrap = file_get_contents($cfg->bootstrap);
    
    if ($bootstrap === false) {
        throw new Exception("Failed to extract the file content of the bootstrap file");
    }
}

$stdout->println("Creating bootstrap");

foreach (["meta" => $cfg->meta, "header.php" => $cfg->header, "default.php" => $cfg->stub, "index.php" => $cfg->webstub] as $file => $path) {
    if ($path !== null) {
        $stdout->println("  Adding additional file %s", $file);
    
        if (!$cfg->debug && str_ends_with($file, ".php")) {
            $content = php_strip_whitespace($path);

        } else {
            $content = file_get_contents($path);
        }
        
        if ($content === false) {
            throw new Exception("Failed to extract the file content of '$path'");
        }
        
        $phar->addFromString($file, $content);
    }
}

$phar->setStub($bootstrap);
 
